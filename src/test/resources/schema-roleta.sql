CREATE TABLE ACAO_CARTA (
 ID_ACAO NUMBER PRIMARY KEY REFERENCES ACAO(ID_ACAO),
 ID_CARTA NUMBER NOT NULL REFERENCES CARTA(ID_CARTA),
 NR_CHANCE NUMBER(3) NOT NULL CHECK (NR_CHANCE BETWEEN 1 AND 100),
 QT_DUPLICADA NUMBER(3) NOT NULL CHECK (QT_DUPLICADA BETWEEN 1 AND 100)
);
CREATE TABLE ROLETA_RESULTADO (
 ID_VERIFICACAO VARCHAR2(36 CHAR) PRIMARY KEY REFERENCES VERIFICACAO(ID_VERIFICACAO),
 ID_USUARIO NUMBER NOT NULL REFERENCES USUARIO(ID_USUARIO),
 ID_CARTA NUMBER NOT NULL REFERENCES CARTA(ID_CARTA),
 NR_CHANCE NUMBER(3) NOT NULL CHECK (NR_CHANCE BETWEEN 1 AND 100),
 ST_GANHOU NUMBER(1) NOT NULL CHECK (ST_GANHOU IN (0,1)),
 ST_DUPLICADA NUMBER(1) NOT NULL CHECK (ST_DUPLICADA IN (0,1)),
 QT_FRAGMENTOS NUMBER(3) DEFAULT 0 NOT NULL CHECK (QT_FRAGMENTOS BETWEEN 0 AND 100),
 DT_GIRO TIMESTAMP NOT NULL,
 CONSTRAINT CK_ROLETA_DUPLICADA CHECK (ST_DUPLICADA <= ST_GANHOU),
 CONSTRAINT CK_ROLETA_FRAGMENTOS CHECK ((ST_DUPLICADA=1 AND QT_FRAGMENTOS>0) OR (ST_DUPLICADA=0 AND QT_FRAGMENTOS=0))
);
CREATE INDEX IX_ROLETA_USUARIO ON ROLETA_RESULTADO(ID_USUARIO,DT_GIRO);
