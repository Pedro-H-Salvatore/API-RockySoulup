-- Complemento do catalogo original: somente as 13 acoes ausentes.
-- Preserva IDs, nomes e pontuacao dos registros existentes.
-- Reexecutavel sem duplicar nomes equivalentes por caixa/espacos.

MERGE INTO ACAO target
USING (SELECT 'Compostagem' NM_ACAO, 30 NR_PONTOS FROM DUAL) source
ON (UPPER(TRIM(target.NM_ACAO)) = UPPER(TRIM(source.NM_ACAO)))
WHEN NOT MATCHED THEN INSERT (NM_ACAO, NR_PONTOS, NR_VERSAO)
VALUES (source.NM_ACAO, source.NR_PONTOS, 0);

