-- Adiciona somente a tabela de desafios e seus indices; preserva dados existentes.
CREATE TABLE CAPTURA_DESAFIO (
 ID_DESAFIO VARCHAR2(36 CHAR) PRIMARY KEY,
 ID_USUARIO NUMBER NOT NULL REFERENCES USUARIO(ID_USUARIO),
 ID_ACAO NUMBER NOT NULL REFERENCES ACAO(ID_ACAO),
 DS_CODIGO VARCHAR2(6 CHAR) NOT NULL,
 DS_IP_HASH VARCHAR2(64 CHAR) NOT NULL,
 DT_CRIADO TIMESTAMP NOT NULL,
 DT_EXPIRA TIMESTAMP NOT NULL,
 DT_USADO TIMESTAMP,
 ID_VERIFICACAO VARCHAR2(36 CHAR) UNIQUE REFERENCES VERIFICACAO(ID_VERIFICACAO),
 DS_HASH_VISUAL VARCHAR2(16 CHAR),
 CONSTRAINT CK_CAPTURA_USO CHECK ((DT_USADO IS NULL AND ID_VERIFICACAO IS NULL) OR (DT_USADO IS NOT NULL AND ID_VERIFICACAO IS NOT NULL)),
 CONSTRAINT CK_CAPTURA_PRAZO CHECK (DT_EXPIRA > DT_CRIADO)
);
CREATE INDEX IX_CAPTURA_USUARIO ON CAPTURA_DESAFIO (ID_USUARIO, DT_CRIADO);
CREATE INDEX IX_CAPTURA_CRIADO ON CAPTURA_DESAFIO (DT_CRIADO);
CREATE INDEX IX_CAPTURA_IP ON CAPTURA_DESAFIO (DS_IP_HASH, DT_CRIADO);
