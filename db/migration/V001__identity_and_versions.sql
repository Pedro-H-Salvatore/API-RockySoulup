-- Review and execute offline using a schema owner, never the runtime account.
-- Oracle DDL commits implicitly. Take a verified backup before executing.
WHENEVER SQLERROR EXIT FAILURE ROLLBACK;

DECLARE
  duplicates NUMBER;
BEGIN
  SELECT COUNT(*) INTO duplicates FROM
    (SELECT LOWER(TRIM(DS_EMAIL)) FROM USUARIO GROUP BY LOWER(TRIM(DS_EMAIL)) HAVING COUNT(*) > 1);
  IF duplicates > 0 THEN
    RAISE_APPLICATION_ERROR(-20001, 'Resolve duplicate normalized emails before migration');
  END IF;
END;
/
UPDATE USUARIO SET DS_EMAIL = LOWER(TRIM(DS_EMAIL));
COMMIT;
CREATE UNIQUE INDEX UK_USUARIO_EMAIL_NORMAL ON USUARIO (LOWER(TRIM(DS_EMAIL)));
ALTER TABLE USUARIO ADD (
  DS_SENHA_HASH VARCHAR2(60 CHAR),
  DS_PERFIL VARCHAR2(5 CHAR) DEFAULT 'USER' NOT NULL,
  ST_ATIVO NUMBER(1) DEFAULT 0 NOT NULL,
  NR_TOKEN_VERSION NUMBER(19) DEFAULT 0 NOT NULL,
  NR_VERSAO NUMBER(19) DEFAULT 0 NOT NULL
);
ALTER TABLE USUARIO ADD CONSTRAINT CK_USUARIO_PERFIL CHECK (DS_PERFIL IN ('USER','ADMIN'));
ALTER TABLE USUARIO ADD CONSTRAINT CK_USUARIO_ATIVO CHECK (ST_ATIVO IN (0,1));
ALTER TABLE USUARIO ADD CONSTRAINT CK_USUARIO_HASH CHECK (ST_ATIVO = 0 OR DS_SENHA_HASH IS NOT NULL);
ALTER TABLE USUARIO ADD CONSTRAINT CK_USUARIO_TOKEN_VERSION CHECK (NR_TOKEN_VERSION >= 0);
ALTER TABLE USUARIO ADD CONSTRAINT CK_USUARIO_VERSAO CHECK (NR_VERSAO >= 0);
ALTER TABLE USUARIO ADD CONSTRAINT CK_USUARIO_EMAIL_NORMAL CHECK (DS_EMAIL = LOWER(TRIM(DS_EMAIL)));

ALTER TABLE ACAO ADD NR_VERSAO NUMBER(19) DEFAULT 0 NOT NULL;
ALTER TABLE CARTA ADD NR_VERSAO NUMBER(19) DEFAULT 0 NOT NULL;
ALTER TABLE SELO ADD NR_VERSAO NUMBER(19) DEFAULT 0 NOT NULL;
ALTER TABLE RECOMPENSA ADD NR_VERSAO NUMBER(19) DEFAULT 0 NOT NULL;
ALTER TABLE HISTORICO ADD NR_VERSAO NUMBER(19) DEFAULT 0 NOT NULL;
ALTER TABLE USUARIO_CARTA ADD NR_VERSAO NUMBER(19) DEFAULT 0 NOT NULL;
ALTER TABLE USUARIO_FRAGMENTO ADD NR_VERSAO NUMBER(19) DEFAULT 0 NOT NULL;
